"""Generates lib/Keymap/KeymapCompose.inc: base letter + combining accent -> precomposed letter,
for every precomposed letter in Latin-1, Latin Extended-A and Cyrillic (the ranges the built-in
fonts cover). Run: python test/keymap/gen_compose.py > lib/Keymap/KeymapCompose.inc
"""
import unicodedata

MARKS = [0x0300, 0x0301, 0x0302, 0x0303, 0x0304, 0x0306, 0x0307, 0x0308, 0x030A, 0x030B, 0x030C, 0x0327, 0x0328]
rows = []
for cp in list(range(0xC0, 0x180)) + list(range(0x400, 0x500)):
    d = unicodedata.decomposition(chr(cp)).split()
    if len(d) != 2 or d[0].startswith('<'):
        continue
    base, mark = int(d[0], 16), int(d[1], 16)
    if mark in MARKS and base < 0x10000:
        rows.append((base, MARKS.index(mark), cp))
rows.sort()
print("// Generated by test/keymap/gen_compose.py from Python's Unicode data. Do not edit.")
print("// {base, accent index into kComposeMarks, result}")
print("static const uint16_t kComposeMarks[] = {" + ", ".join("0x%04X" % m for m in MARKS) + "};")
print("static const ComposeEntry kComposeTable[] = {")
for i in range(0, len(rows), 6):
    print("  " + " ".join("{0x%04X, %d, 0x%04X}," % r for r in rows[i:i + 6]))
print("};")
