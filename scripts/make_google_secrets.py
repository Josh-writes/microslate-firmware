"""Turns the JSON downloaded from the Google Cloud console (Clients > MicroSlate device > Download JSON)
into src/sync/secrets.local.h. Prints only whether it worked, never the values.
Usage: python scripts/make_google_secrets.py src/sync/google-client.local.json"""
import json, sys, pathlib

src = pathlib.Path(sys.argv[1])
data = json.loads(src.read_text(encoding="utf-8"))
block = data.get("installed") or data.get("web") or {}
cid, secret = block.get("client_id", ""), block.get("client_secret", "")
if not cid or not secret:
    sys.exit("The file has no client_id / client_secret")
out = pathlib.Path(__file__).resolve().parent.parent / "src" / "sync" / "secrets.local.h"
out.write_text(
    "#pragma once\n"
    "// LOCAL ONLY. Ignored by git. Generated by scripts/make_google_secrets.py from the Google console download.\n"
    "// Google treats a device client's secret as non-confidential (it ships in the firmware), but it stays out of the public repo.\n"
    f'#define MS_GOOGLE_CLIENT_ID "{cid}"\n'
    f'#define MS_GOOGLE_CLIENT_SECRET "{secret}"\n',
    encoding="utf-8")
print("secrets.local.h written (client id ends in ..." + cid[-30:] + ", secret length %d)" % len(secret))
